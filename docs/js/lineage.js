// "Where the data comes from": the warehouse lineage diagram. Nodes are buttons laid out by CSS
// (columns on wide screens, stacked rows on narrow ones). Edges are drawn in an
// SVG overlay from the buttons' measured positions.

import { $, h, s, fmt, get, isNum, setHTML, numSpan, esc } from "./util.js";

const LAYERS = [
  { key: "source", title: "Source files" },
  { key: "staging", title: "Staging" },
  { key: "intermediate", title: "Intermediate" },
  { key: "mart", title: "Marts" },
];

export function initLineage(pipeline, summary) {
  const src = get(pipeline, "source", {});
  const nodes = get(pipeline, "nodes", []);
  const edges = get(pipeline, "edges", []).filter((e) => Array.isArray(e) && e.length === 2);
  const tests = get(pipeline, "tests");

  setHTML("data-intro",
    `The patients are synthetic, generated by ${esc(src.generator || "Synthea")} with a fixed seed` +
    (isNum(src.n_patients) ? ` (${numSpan(fmt.int(src.n_patients))} patients${src.state ? ", " + esc(src.state) : ""}${src.date_start ? `, records from ${esc(String(src.date_start).slice(0, 4))} to ${esc(String(src.date_end).slice(0, 4))}` : ""})` : "") +
    `. The raw files go through a dbt project into one modeling table with one row per member per January 1` +
    (isNum(get(summary, "data.n_member_years")) ? `: ${numSpan(fmt.int(summary.data.n_member_years))} member-years` +
      (isNum(get(summary, "data.n_members")) ? ` from ${numSpan(fmt.int(summary.data.n_members))} adult members` : "") + ` and ${numSpan(fmt.int(summary.data.n_features))} features.` : "."));
  if (tests && isNum(tests.total)) {
    setHTML("data-gloss", `${fmt.int(tests.passed)} of ${fmt.int(tests.total)} dbt tests pass.`);
    setHTML("tests-line",
      (tests.failed > 0
        ? `${numSpan(fmt.int(tests.failed))} of ${numSpan(fmt.int(tests.total))} dbt tests fail on this build.`
        : `All ${numSpan(fmt.int(tests.total))} dbt tests pass on this build`) +
      (tests.failed > 0 ? "" : get(tests, "by_type.generic") !== undefined ? ` (${numSpan(fmt.int(tests.by_type.generic))} generic, ${numSpan(fmt.int(tests.by_type.singular))} written for this project).` : ".") +
      " The ones below exist to catch a model that sees the future.");
  }
  const checks = get(pipeline, "leakage_checks", []);
  $("leakage").replaceChildren(...checks.map((c) =>
    h("li", {},
      h("span", {}, h("span", { class: `tag${c.result === "pass" ? "" : " solid"}`, text: c.result === "pass" ? "Pass" : "Fail" })),
      h("span", { text: c.name }),
      c.detail ? h("span", { class: "detail" }, c.detail, c.test ? h("span", {}, " Test: ", h("code", { text: c.test })) : null) : null)
  ));

  if (!nodes.length) throw new Error("pipeline has no nodes");
  const root = $("lineage");
  const svg = s("svg", { "aria-hidden": "true" });
  root.append(svg);
  const byId = new Map();
  LAYERS.forEach((layer) => {
    const mine = nodes.filter((n) => n.layer === layer.key);
    if (!mine.length) return;
    const box = h("div", { class: "nodes" });
    mine.forEach((n) => {
      const btn = h("button", { type: "button", class: "node", "aria-pressed": "false" },
        h("span", { class: "nm", html: esc(n.label || n.id).replace(/_/g, "_<wbr>") }),
        h("span", { class: "rows", text: isNum(n.rows) ? `${fmt.compact(n.rows)} rows` : "" }));
      btn.addEventListener("click", () => select(selected === n.id ? null : n.id));
      byId.set(n.id, { node: n, btn });
      box.append(btn);
    });
    root.append(h("div", { class: "layer" }, h("h4", {}, layer.title, " ", h("span", { text: `(${mine.length})` })), box));
  });

  const up = new Map(), down = new Map();
  edges.forEach(([a, b]) => {
    if (!byId.has(a) || !byId.has(b)) return;
    (down.get(a) || down.set(a, []).get(a)).push(b);
    (up.get(b) || up.set(b, []).get(b)).push(a);
  });
  const closure = (start, map) => {
    const seen = new Set();
    const stack = [start];
    while (stack.length) {
      for (const nxt of map.get(stack.pop()) || []) if (!seen.has(nxt)) { seen.add(nxt); stack.push(nxt); }
    }
    return seen;
  };

  let selected = null;
  let paths = [];
  function drawEdges() {
    const box = root.getBoundingClientRect();
    const horizontal = window.matchMedia("(min-width: 860px)").matches;
    svg.replaceChildren();
    paths = [];
    edges.forEach(([a, b]) => {
      const A = byId.get(a), B = byId.get(b);
      if (!A || !B) return;
      const ra = A.btn.getBoundingClientRect(), rb = B.btn.getBoundingClientRect();
      const same = A.node.layer === B.node.layer;
      let d;
      if (horizontal) {
        const x1 = ra.right - box.left, y1 = ra.top + ra.height / 2 - box.top;
        if (same) {
          const x2 = rb.right - box.left, y2 = rb.top + rb.height / 2 - box.top;
          const bulge = 16 + Math.min(18, Math.abs(y2 - y1) / 8);
          d = `M${x1},${y1} C${x1 + bulge},${y1} ${x2 + bulge},${y2} ${x2},${y2}`;
        } else {
          const x2 = rb.left - box.left, y2 = rb.top + rb.height / 2 - box.top;
          const mid = (x1 + x2) / 2;
          d = `M${x1},${y1} C${mid},${y1} ${mid},${y2} ${x2},${y2}`;
        }
      } else {
        const x1 = ra.left + ra.width / 2 - box.left, y1 = ra.bottom - box.top;
        const x2 = rb.left + rb.width / 2 - box.left;
        if (same) {
          const y2 = rb.bottom - box.top;
          const dip = Math.max(y1, y2) + 14;
          d = `M${x1},${y1} C${x1},${dip} ${x2},${dip} ${x2},${y2}`;
        } else {
          const y2 = rb.top - box.top;
          const mid = (y1 + y2) / 2;
          d = `M${x1},${y1} C${x1},${mid} ${x2},${mid} ${x2},${y2}`;
        }
      }
      const path = s("path", { d });
      svg.append(path);
      paths.push({ a, b, path });
    });
    mark();
  }

  function mark() {
    const rel = selected ? new Set([selected, ...closure(selected, up), ...closure(selected, down)]) : new Set();
    root.classList.toggle("has-sel", !!selected);
    byId.forEach(({ btn }, id) => {
      btn.setAttribute("aria-pressed", String(id === selected));
      btn.classList.toggle("rel", rel.has(id));
    });
    paths.forEach((p) => p.path.classList.toggle("on", rel.has(p.a) && rel.has(p.b)));
  }

  function select(id) {
    selected = id;
    mark();
    const detail = $("node-detail");
    if (!id) return detail.replaceChildren(h("p", { text: "No table selected." }));
    const n = byId.get(id).node;
    const parents = up.get(id) || [];
    const kids = down.get(id) || [];
    const chips = (ids) => ids.map((other) => {
      const b = h("button", { type: "button", class: "chip", text: (byId.get(other).node.label || other) });
      b.addEventListener("click", () => select(other));
      return b;
    });
    detail.replaceChildren(...[
      h("p", {},
        h("span", { class: "nm", text: n.label || n.id }),
        isNum(n.rows) ? ` has ${fmt.int(n.rows)} rows. ` : ". ",
        n.description || ""),
      parents.length ? h("div", { class: "rel-row" }, "Built from ", chips(parents)) : null,
      kids.length ? h("div", { class: "rel-row" }, "Feeds ", chips(kids)) : null,
    ].filter(Boolean));
  }

  new ResizeObserver(() => requestAnimationFrame(drawEdges)).observe(root);
  if (document.fonts && document.fonts.ready) document.fonts.ready.then(drawEdges);
  // open on the mart with the longest lineage behind it (the modeling table)
  const first = nodes.filter((n) => n.layer === "mart").sort((a, b) => closure(b.id, up).size - closure(a.id, up).size)[0];
  drawEdges();
  if (first) select(first.id);
}
